def parse_params(text):
    out = []
    for chunk in text.split(","):
        chunk = chunk.strip()
        if not chunk:
            continue
        if "=" not in chunk:
            raise SystemExit(f"bad --params entry {chunk!r}, expected name=value")
        k, v = chunk.split("=", 1)
        k = k.strip()
        if not re.fullmatch(r"[a-z_][a-z0-9_]*", k):
            raise SystemExit(f"parameter {k!r} must be lower_snake_case "
                             "(it becomes both a Python key and a slider id)")
        out.append((k, float(v)))
    if not out:
        raise SystemExit("--params must define at least one parameter")
    return out


def slider(k, v):
    """A sane starting range: half to double, clamped away from zero."""
    lo = round(max(v * 0.5, 0.1), 2) if v > 0 else 0.0
    hi = round(max(v * 2.0, v + 1.0), 2)
    step = 0.1 if v < 10 else (0.5 if v < 60 else 1)
    label = k.replace("_", " ").capitalize()
    return (f'    {{id:"{k}",fs:"{k.upper()}",u:"MM",g:"Main",'
            f'label:"{label}",min:{lo},max:{hi},step:{step},val:{v:g}}}')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True,
                    help="lower_snake_case, e.g. spacer_plate")
    ap.add_argument("--params", required=True,
                    help='comma separated name=value, e.g. "w=90,d=50,t=4"')
    ap.add_argument("--project", default=None,
                    help="project directory (default: current directory)")
    ap.add_argument("--examples", action="store_true",
                    help="write into the skill's own models/ folder")
    ap.add_argument("--label", default=None, help="human name for the picker")
    a = ap.parse_args()

    if not re.fullmatch(r"[a-z_][a-z0-9_]*", a.name):
        raise SystemExit("--name must be lower_snake_case")

    params = parse_params(a.params)
    first = f"{params[0][1]:g}"
    label = a.label or a.name.replace("_", " ").capitalize()
    key = a.name.replace("_", "-")

    if a.examples:
        root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
        models = os.path.join(root, "models")
        os.makedirs(models, exist_ok=True)
        rel = f"models/{a.name}.py"
    else:
        from cadproj import open_project
        proj = open_project(a.project or os.getcwd())
        models = str(proj.parts)
        rel = f"cad/parts/{a.name}.py"
    scripts = os.path.dirname(os.path.abspath(__file__))

    mp = os.path.join(models, f"{a.name}.py")
    rp = os.path.join(models, f"{a.name}.recipe.js")
    for p in (mp, rp):
        if os.path.exists(p):
            raise SystemExit(f"{p} already exists -- refusing to overwrite")

    with open(mp, "w", encoding="utf-8") as fh:
        fh.write(MODEL.format(
            name=a.name, first=first, scripts=scripts,
            params="\n".join(f'    "{k}": {v!r},' for k, v in params)))
    with open(rp, "w", encoding="utf-8") as fh:
        fh.write(RECIPE.format(
            key=key, label=label, name=a.name, first=first, file=rel,
            sliders=",\n".join(slider(k, v) for k, v in params)))

    print(f"wrote {mp}")
    print(f"wrote {rp}")
    print(f"\nnext: run it as-is to confirm the harness works --")
    print(f"    python {mp}")
    print("then replace derive()/build() and the recipe's checks()/draw().")


if __name__ == "__main__":
    main()
